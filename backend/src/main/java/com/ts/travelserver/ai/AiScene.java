package com.ts.travelserver.ai;

/**
 * AI 调用场景。写进 ai_log.scene，也是缓存键的一部分。
 *
 * <p>只有三个场景是「真需要模型」的（规则写不出来的那部分）：
 * 一个是读懂一句话（语义 Δ），另两个是生成一句话（事由改写、月报解读）。
 * 其余能力（挂段、可疑模式、风险摘要、月报结论）是确定性规则，不进模型，
 * 也就不占这里的场景——它们是「AI 功能」，但不是「模型调用」。
 *
 * <p>三个场景的共同边界：<b>给模型的数据全部来自本库，模型不联网</b>。
 * 联网这条路评估过，不接：在 /chat/completions 上联网会被拒，
 * 换成 Responses API 之后又拿不到引用地址，结论无法锚定 evidence——
 * 与本项目「每条 AI 结论都要能溯源」的口径冲突。详见 {@code AiPrompts} 的注释。
 */
public final class AiScene {

    /** 语义评价 Δ：读事由与行程，输出 −10 ~ +5 的调节分 */
    public static final String SEMANTIC_EVAL = "SEMANTIC_EVAL";

    /**
     * 填写助手：事由改写，入参里带上库内上下文（同类花费、差标上限、对象产出、本人历史）。
     *
     * <p>带上下文是为了让模型写出「跟进已有合作」这类话——
     * 它得先知道这个对象是不是已经合作过。
     */
    public static final String APPLY_ASSIST = "APPLY_ASSIST";

    /**
     * 月度洞察：把费效比月报的一堆统计数字归纳成几条能直接看的结论。
     *
     * <p>这是全系统唯一「模型读数字、但不许算数字」的场景：
     * 投入、产出、费效比、归因贡献全部由 {@code AnalyticsService} 算好放进输入，
     * 模型只负责挑重点、组织措辞。输出里出现任何输入中不存在的数字都会被整条丢弃——
     * 宁可少说一句，也不能让页面出现一个来源不明的数。
     */
    public static final String MONTHLY_INSIGHT = "MONTHLY_INSIGHT";

    /**
     * 钻取解释：管理层点开某个部门，问「这个月为什么变了」。
     *
     * <p>与月度洞察同一条边界——投入、产出、费效比、环比全部由统计层算好放进输入，
     * 模型只回答「为什么」。不同的是它<b>按次触发</b>：只有人点了「看分析」才调一次，
     * 切部门、切月份都不自动跑。这不是为了省钱，是因为它是「人问了一句」才有的答复，
     * 主动冒出来就成了又一块自动生成的文字。
     */
    public static final String DRILL_EXPLAIN = "DRILL_EXPLAIN";

    /**
     * 制度问答：员工问一句「去深圳能报多少」，系统把库里现行的差标与规则查出来，
     * 让模型照着组织成一句话。
     *
     * <p>这是三个场景里唯一「事实先查、模型后说」之外还多一道的：
     * <b>查不到就说查不到</b>。差标表里没有的东西（比如报销时限、差旅补贴天数）
     * 必须原样回答「库里没有这一条」，不许用行业惯例填补——
     * 填补出来的答案看着专业，但没人能对它负责。
     *
     * <p>刻意不做向量库：知识源全在 MySQL 里而且是结构化的（差标表、部门预算、
     * 超标比例），一条 SQL 就能取全，检索这一步根本用不着语义匹配。
     * 只有开始问「出差期间生病怎么报销」这类散在文档的问题，才需要真 RAG。
     */
    public static final String POLICY_QA = "POLICY_QA";

    /**
     * 问数助手：管理层用大白话问「9 月技术部费效比多少」「哪个客户最不划算」，
     * 系统把真实业务数字算出来，让模型组织成一句人话。
     *
     * <p>与前面五个场景最大的不同：它<b>不靠模型的 function calling</b>。
     * 能问什么由 {@code DataQaService} 里一份写死的「能力目录」决定
     * （某月费效比 / 对象投入产出 Top / 某人某月出差 / 部门预算余额 / 超时未批单），
     * 模型只在前端已经算出真实数字之后，负责把数字讲成一句通顺的话——
     * 这样换一个不认 tool_calling 的国产模型也不会失效，
     * 也不存在「模型调了个不存在的接口」这种幻觉出口。
     *
     * <p>三条边界与全系统一致：
     * <ul>
     *   <li><b>不联网</b>：数字全部来自本库 Service，模型看不到任何外部信息。</li>
     *   <li><b>不算数</b>：意图解析（月份 / 部门 / 人名）由 Java 做，
     *       模型既不算数也不决定调哪个能力，它只做叙事。</li>
     *   <li><b>每条带 evidence</b>：叙事里出现的每个数字都要能落回 Java 算出的真实值，
     *       落不回的整句丢弃，回落到「库里查到：XXX」这种规则文案。</li>
     * </ul>
     *
     * <p>降级比别的场景更彻底一层：模型不可用（{@code MockAiService}）时，
     * 不是返回空，而是直接把算好的真实数字原样陈列出来——
     * 问数助手要的是「把数说出来」，模型挂了，数照样能说。
     */
    public static final String DATA_QA = "DATA_QA";

    private AiScene() {
    }
}
